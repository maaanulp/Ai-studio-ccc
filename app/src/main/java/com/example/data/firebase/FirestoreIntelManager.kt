package com.example.data.firebase

import android.content.Context
import android.util.Log
import com.example.R
import com.example.data.model.TargetEntity
import com.google.firebase.Firebase
import com.google.firebase.auth.auth
import com.google.firebase.firestore.FieldValue
import com.google.firebase.firestore.FirebaseFirestore
import com.google.firebase.firestore.SetOptions
import kotlinx.coroutines.channels.awaitClose
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.callbackFlow
import kotlinx.coroutines.tasks.await

private const val TAG = "FirestoreIntelManager"

/**
 * Manages Firebase Firestore storage using the custom database ID.
 * Scopes all read and write queries under the authenticated user.
 */
class FirestoreIntelManager(private val context: Context) {
    // Custom database ID from firebase_applet_config.xml is strictly required
    private val db: FirebaseFirestore = FirebaseFirestore.getInstance(
        context.getString(R.string.firestore_database_id)
    )

    private val auth = Firebase.auth

    private fun requireUserId(): String {
        return auth.currentUser?.uid ?: error("User must be authenticated to perform Firestore operations.")
    }

    /**
     * Syncs target intelligence to Firestore under /users/{userId}/targets/{targetId}
     */
    suspend fun syncTargetToCloud(target: TargetEntity): Result<Unit> {
        return try {
            val uid = requireUserId()
            val targetDocId = if (target.ip.isNotBlank() && !target.ip.startsWith("Pending")) {
                target.ip.replace(".", "_")
            } else {
                "target_${target.id}"
            }

            val targetData = hashMapOf(
                "targetId" to targetDocId,
                "userId" to uid,
                "ip" to target.ip,
                "name" to target.name,
                "level" to target.level,
                "fw" to target.fw,
                "enc" to target.enc,
                "wallet" to target.wallet,
                "crew" to target.crew,
                "stolenCrypto" to target.stolenCrypto,
                "notes" to target.notes,
                "updatedAt" to FieldValue.serverTimestamp()
            )

            db.collection("users")
                .document(uid)
                .collection("targets")
                .document(targetDocId)
                .set(targetData, SetOptions.merge())
                .await()

            Result.success(Unit)
        } catch (e: Exception) {
            Log.e(TAG, "Failed to sync target to Firestore", e)
            Result.failure(e)
        }
    }

    /**
     * Syncs general target intelligence to shared crew collection under /crews/{crewId}/general_targets/{targetDocId}
     */
    suspend fun syncGeneralTargetToCrew(target: TargetEntity, crewId: String): Result<Unit> {
        return try {
            val uid = try { requireUserId() } catch (e: Exception) { "anonymous" }
            val cleanCrew = crewId.ifBlank { "CRYPT0_CREW" }
            val targetDocId = if (target.ip.isNotBlank() && !target.ip.startsWith("Pending")) {
                target.ip.replace(".", "_")
            } else {
                "target_${target.id}"
            }

            val targetData = hashMapOf(
                "targetId" to targetDocId,
                "contributorId" to uid,
                "ip" to target.ip,
                "name" to target.name,
                "level" to target.level,
                "fw" to target.fw,
                "enc" to target.enc,
                "wallet" to target.wallet,
                "crew" to cleanCrew,
                "stolenCrypto" to target.stolenCrypto,
                "notes" to target.notes,
                "updatedAt" to FieldValue.serverTimestamp()
            )

            db.collection("crews")
                .document(cleanCrew)
                .collection("general_targets")
                .document(targetDocId)
                .set(targetData, SetOptions.merge())
                .await()

            Result.success(Unit)
        } catch (e: Exception) {
            Log.e(TAG, "Failed to sync general target to crew Firestore", e)
            Result.failure(e)
        }
    }

    /**
     * Saves an intelligence report generated by Gemini AI to Firestore under /users/{userId}/intelligence_reports/{reportId}
     */
    suspend fun saveIntelligenceReport(
        title: String,
        summary: String,
        rawText: String,
        engine: String
    ): Result<String> {
        return try {
            val uid = requireUserId()
            val reportDoc = db.collection("users")
                .document(uid)
                .collection("intelligence_reports")
                .document()

            val reportData = hashMapOf(
                "reportId" to reportDoc.id,
                "userId" to uid,
                "title" to title,
                "summary" to summary,
                "rawText" to rawText,
                "engine" to engine,
                "createdAt" to FieldValue.serverTimestamp()
            )

            reportDoc.set(reportData).await()
            Result.success(reportDoc.id)
        } catch (e: Exception) {
            Log.e(TAG, "Failed to save intel report to Firestore", e)
            Result.failure(e)
        }
    }

    /**
     * Creates or updates user operative profile upon successful sign in
     */
    suspend fun ensureUserProfile(email: String, displayName: String?, crew: String?): Result<Unit> {
        return try {
            val uid = requireUserId()
            val userDoc = db.collection("users").document(uid)
            val snapshot = userDoc.get().await()
            if (!snapshot.exists()) {
                val userData = hashMapOf(
                    "userId" to uid,
                    "email" to email,
                    "displayName" to (displayName ?: "Operative-${uid.take(5)}"),
                    "crew" to (crew ?: "Crypt0 Cr3w"),
                    "createdAt" to FieldValue.serverTimestamp()
                )
                userDoc.set(userData).await()
            }
            Result.success(Unit)
        } catch (e: Exception) {
            Log.e(TAG, "Failed to ensure user profile", e)
            Result.failure(e)
        }
    }

    /**
     * Realtime flow of cloud-stored target documents
     */
    fun observeCloudTargets(): Flow<List<Map<String, Any?>>> = callbackFlow {
        val uid = auth.currentUser?.uid
        if (uid == null) {
            trySend(emptyList())
            close()
            return@callbackFlow
        }

        val listener = db.collection("users")
            .document(uid)
            .collection("targets")
            .addSnapshotListener { snapshot, error ->
                if (error != null) {
                    Log.e(TAG, "Error observing cloud targets", error)
                    return@addSnapshotListener
                }
                val list = snapshot?.documents?.mapNotNull { it.data } ?: emptyList()
                trySend(list)
            }

        awaitClose { listener.remove() }
    }

    suspend fun publishFeedPost(post: com.example.data.model.FeedPostEntity): Result<String> {
        return try {
            val postDoc = db.collection("crews").document(post.crewId).collection("feed_posts").document()
            
            val postData = hashMapOf(
                "id" to postDoc.id,
                "scope" to post.scope,
                "crewId" to post.crewId,
                "author" to post.author,
                "title" to post.title,
                "tag" to post.tag,
                "content" to post.content,
                "createdAt" to FieldValue.serverTimestamp()
            )
            postDoc.set(postData).await()
            Result.success(postDoc.id)
        } catch (e: Exception) {
            Result.failure(e)
        }
    }
}
